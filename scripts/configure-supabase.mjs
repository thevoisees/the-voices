#!/usr/bin/env node
/**
 * Wire Supabase into local .env and GitHub Actions secrets for Pages.
 *
 * Usage:
 *   node scripts/configure-supabase.mjs "https://xxxx.supabase.co" "eyJhbGciOi..."
 *
 * Get URL + anon key from: Supabase Dashboard → Project Settings → API
 * First run supabase/schema.sql in the SQL Editor (tables + photo bucket).
 */
import { writeFileSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'
import { spawnSync } from 'node:child_process'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const url = process.argv[2]
const key = process.argv[3]

if (!url || !key) {
  console.error(`Usage:
  node scripts/configure-supabase.mjs "<VITE_SUPABASE_URL>" "<VITE_SUPABASE_ANON_KEY>"

1) Create a project at https://supabase.com
2) SQL Editor → paste & run supabase/schema.sql
3) Project Settings → API → copy Project URL + anon public key
4) Run this script with those two values
`)
  process.exit(1)
}

if (!/^https:\/\/.+\.supabase\.co\/?$/.test(url.replace(/\/$/, '') + '/') && !url.includes('supabase.co')) {
  console.warn('Warning: URL does not look like a supabase.co project URL')
}

const envBody = `# Generated by scripts/configure-supabase.mjs
VITE_SUPABASE_URL=${url.replace(/\/$/, '')}
VITE_SUPABASE_ANON_KEY=${key}
`
writeFileSync(resolve(root, '.env'), envBody)
console.log('Wrote .env for local npm run dev')

const gh = spawnSync(
  'gh',
  ['secret', 'set', 'VITE_SUPABASE_URL', '-R', 'thevoisees/the-voices', '-b', url.replace(/\/$/, '')],
  { encoding: 'utf8' },
)
if (gh.status !== 0) {
  console.warn('Could not set GitHub secret VITE_SUPABASE_URL:', gh.stderr || gh.stdout)
} else {
  console.log('Set GitHub secret VITE_SUPABASE_URL')
}

const gh2 = spawnSync(
  'gh',
  ['secret', 'set', 'VITE_SUPABASE_ANON_KEY', '-R', 'thevoisees/the-voices', '-b', key],
  { encoding: 'utf8' },
)
if (gh2.status !== 0) {
  console.warn('Could not set GitHub secret VITE_SUPABASE_ANON_KEY:', gh2.stderr || gh2.stdout)
} else {
  console.log('Set GitHub secret VITE_SUPABASE_ANON_KEY')
}

console.log(`
Next:
  1. Confirm schema.sql was run (tables + missing-photos bucket)
  2. npm run dev   — check About → “Supabase connected”
  3. git commit --allow-empty -m "chore: rebuild with Supabase" && git push
     (or any push) so Pages rebuilds with the secrets
`)
